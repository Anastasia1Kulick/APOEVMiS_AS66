// Лабораторная работа №2, вариант 6. Процедуры обработки текста на ассемблере.
// Платформа: Mac с процессором Apple (ARM64), ассемблер Clang.
//
// Текст хранится в кодировке Windows-1251, один символ = один байт:
//   'A'..'Z'  = 0x41..0x5A     'a'..'z' = 0x61..0x7A
//   'А'..'Я'  = 0xC0..0xDF     'Ё'      = 0xA8
//
// Во всех процедурах: x0 = адрес первого символа, x1 = длина текста в байтах,
// результат (если есть) возвращается в w0. Дополнительная память не используется:
// всё хранится в регистрах. Глобальных переменных нет.

    .text
    .align 2

// ---------------------------------------------------------------
// int text_is_valid(const unsigned char* text, long len)
// Возвращает 1, если в тексте нет управляющих символов (код < 0x20 и 0x7F).
// Иначе возвращает 0: последовательность не является текстом.
// ---------------------------------------------------------------
    .globl _text_is_valid
_text_is_valid:
    cbz  x1, Lvalid_yes             // пустой текст нечего проверять
Lvalid_loop:
    ldrb w2, [x0], #1               // w2 = очередной символ, адрес сдвигается на 1
    cmp  w2, #0x20
    b.lo Lvalid_no                  // код меньше 0x20 - управляющий символ
    cmp  w2, #0x7F
    b.eq Lvalid_no                  // код 0x7F (DEL) - тоже управляющий
    subs x1, x1, #1                 // осталось символов на один меньше
    b.ne Lvalid_loop
Lvalid_yes:
    mov  w0, #1
    ret
Lvalid_no:
    mov  w0, #0
    ret

// ---------------------------------------------------------------
// int check_equal_upper(const unsigned char* text, long len)
// Условие варианта 6: количество прописных латинских букв равно
// количеству прописных русских букв. Возвращает 1 (верно) или 0 (неверно).
// w2 - счётчик латинских, w3 - счётчик русских.
// ---------------------------------------------------------------
    .globl _check_equal_upper
_check_equal_upper:
    mov  w2, #0
    mov  w3, #0
    cbz  x1, Lcheck_result
Lcheck_loop:
    ldrb w4, [x0], #1               // w4 = очередной символ
    sub  w5, w4, #0x41              // w5 = код - код 'A'
    cmp  w5, #25                    // беззнаковое сравнение: 0..25 значит 'A'..'Z'
    b.ls Lcheck_latin
    sub  w5, w4, #0xC0              // w5 = код - код 'А'
    cmp  w5, #31                    // 0..31 значит 'А'..'Я'
    b.ls Lcheck_russian
    cmp  w4, #0xA8                  // отдельно проверяем 'Ё'
    b.ne Lcheck_next
Lcheck_russian:
    add  w3, w3, #1
    b    Lcheck_next
Lcheck_latin:
    add  w2, w2, #1
Lcheck_next:
    subs x1, x1, #1
    b.ne Lcheck_loop
Lcheck_result:
    cmp  w2, w3
    cset w0, eq                     // w0 = 1, если счётчики равны, иначе 0
    ret

// ---------------------------------------------------------------
// void swap_latin_case(unsigned char* text, long len)
// Правило варианта 6: строчную латинскую букву заменить прописной,
// а прописную - строчной. Остальные символы не меняются.
// Регистр латинской буквы переключается инверсией бита 5 (число 0x20).
// ---------------------------------------------------------------
    .globl _swap_latin_case
_swap_latin_case:
    cbz  x1, Lswap_done
Lswap_loop:
    ldrb w2, [x0]                   // w2 = символ (адрес пока не сдвигаем)
    orr  w3, w2, #0x20              // w3 = тот же символ, приведённый к строчной
    sub  w3, w3, #0x61              // w3 = код - код 'a'
    cmp  w3, #25                    // 0..25 значит, что это латинская буква
    b.hi Lswap_next
    eor  w2, w2, #0x20              // меняем регистр буквы
    strb w2, [x0]                   // записываем обратно в текст
Lswap_next:
    add  x0, x0, #1
    subs x1, x1, #1
    b.ne Lswap_loop
Lswap_done:
    ret
